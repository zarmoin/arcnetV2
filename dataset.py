"""
PyTorch Dataset & DataLoader with Anti-Underfitting Harmonic Augmentations
for Preprocessed ARCNet-v2 Palette Archives (.npz).

Works directly with the .npz files produced by `preprocess_dataset.py` and feeds
batches into `ARCNetV2` (`arcnet_v2.py`) and `ARCNetV2Loss` (`losses.py`).
"""

import math
from typing import Dict, Optional, Tuple
import numpy as np
import torch
from torch.utils.data import DataLoader, Dataset

from color_space import oklab_to_srgb


class ARCNetPaletteDataset(Dataset):
    """
    Loads precomputed K-cluster palettes from a `.npz` archive generated by
    `preprocess_dataset.py` and applies domain-specific harmonic augmentations:

    1. Dynamic Cluster Count (K in [min_k, max_k]):
       Randomly masks out minor clusters and re-normalizes weights w_k so a single
       model handles variable K in [4, 8] at inference time.
    2. Equivariant Oklab Hue Rotation (hue_rotation_prob):
       Rotates both background and target (a, b) coordinates by a shared random
       angle d_theta in [-pi, pi]. Because classical color harmony is defined by
       relative angular relationships on the hue circle, rotating the entire
       palette preserves harmony while providing infinite chromatic diversity.
    3. Leave-One-Out Target Sampling (leave_one_out_prob):
       Samples any minor cluster k in {2..K} as the target harmonized color and
       uses the remaining K-1 clusters as background context.
    4. Random Background Cluster Permutation:
       Shuffles the K-1 background clusters during training.
    """

    def __init__(
        self,
        npz_path: str,
        split: str = "train",
        min_k: int = 4,
        augment: bool = True,
        hue_rotation_prob: float = 0.5,
        lightness_jitter: float = 0.04,
        leave_one_out_prob: float = 0.3,
    ):
        super().__init__()
        assert split in ("train", "val"), "split must be 'train' or 'val'"
        self.split = split
        self.augment = augment and (split == "train")
        self.hue_rotation_prob = hue_rotation_prob
        self.lightness_jitter = lightness_jitter
        self.leave_one_out_prob = leave_one_out_prob

        data = np.load(npz_path)
        prefix = f"{split}_"

        self.all_srgb = data[f"{prefix}all_srgb"].astype(np.float32)       # [N, K, 3]
        self.all_oklab = data[f"{prefix}all_oklab"].astype(np.float32)     # [N, K, 3]
        self.all_weights = data[f"{prefix}all_weights"].astype(np.float32) # [N, K]
        self.pbr_target = data[f"{prefix}pbr_target"].astype(np.float32)   # [N, 10]

        self.num_samples, self.max_k, _ = self.all_srgb.shape
        self.min_k = max(3, min(min_k, self.max_k))

    def __len__(self) -> int:
        return self.num_samples

    def _rotate_oklab_palette(
        self, oklab: np.ndarray, d_theta: float, d_L: float
    ) -> np.ndarray:
        """Rotate (a, b) in Oklab plane by d_theta and shift L by d_L."""
        cos_t = math.cos(d_theta)
        sin_t = math.sin(d_theta)

        L = np.clip(oklab[..., 0] + d_L, 0.05, 0.98)
        a = oklab[..., 1]
        b = oklab[..., 2]

        a_rot = a * cos_t - b * sin_t
        b_rot = a * sin_t + b * cos_t
        return np.stack([L, a_rot, b_rot], axis=-1).astype(np.float32)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        all_oklab = self.all_oklab[idx].copy()     # [K, 3]
        all_srgb = self.all_srgb[idx].copy()       # [K, 3]
        all_weights = self.all_weights[idx].copy() # [K]
        pbr_target = self.pbr_target[idx].copy()   # [10]

        K = self.max_k
        M = K - 1  # Number of background slots

        # 1. Select which cluster acts as target (default: K-1, the K-th ranked cluster)
        target_idx = K - 1
        if self.augment and np.random.rand() < self.leave_one_out_prob and K > 3:
            # Pick from minor clusters {1, ..., K-1} so dominant cluster #0 stays in bg
            target_idx = int(np.random.randint(1, K))

        bg_indices = [i for i in range(K) if i != target_idx]

        # 2. Optional Oklab Hue Rotation & Lightness Jitter Augmentation
        if self.augment and np.random.rand() < self.hue_rotation_prob:
            d_theta = float(np.random.uniform(-math.pi, math.pi))
            d_L = float(np.random.uniform(-self.lightness_jitter, self.lightness_jitter))
            all_oklab = self._rotate_oklab_palette(all_oklab, d_theta, d_L)
            # Recompute sRGB via torch tensor helper
            all_srgb = oklab_to_srgb(torch.from_numpy(all_oklab)).numpy()

        bg_oklab = all_oklab[bg_indices]      # [K-1, 3]
        bg_srgb = all_srgb[bg_indices]        # [K-1, 3]
        bg_weights = all_weights[bg_indices]  # [K-1]

        target_oklab = all_oklab[target_idx]  # [3]
        target_srgb = all_srgb[target_idx]    # [3]
        pbr_target[0:3] = target_srgb

        # 3. Dynamic K in [min_k, max_k] masking
        mask = np.ones((M,), dtype=bool)
        if self.augment and self.min_k < K:
            active_k = int(np.random.randint(self.min_k, K + 1))
            active_bg = active_k - 1  # in [min_k - 1, K - 1]
            if active_bg < M:
                mask[active_bg:] = False
                bg_weights[~mask] = 0.0

        # Normalize valid background weights to sum to 1
        w_sum = bg_weights.sum()
        if w_sum > 1e-6:
            bg_weights = bg_weights / w_sum
        else:
            bg_weights[mask] = 1.0 / max(1, int(mask.sum()))

        # 4. Randomly permute background clusters during training
        if self.augment:
            perm = np.random.permutation(M)
            bg_oklab = bg_oklab[perm]
            bg_srgb = bg_srgb[perm]
            bg_weights = bg_weights[perm]
            mask = mask[perm]

        return {
            "bg_srgb": torch.from_numpy(bg_srgb),                        # [K-1, 3]
            "bg_oklab": torch.from_numpy(bg_oklab),                      # [K-1, 3]
            "bg_weights": torch.from_numpy(bg_weights).unsqueeze(-1),    # [K-1, 1]
            "mask": torch.from_numpy(mask),                              # [K-1] bool
            "target_srgb": torch.from_numpy(target_srgb),                # [3]
            "target_oklab": torch.from_numpy(target_oklab),              # [3]
            "pbr_target": torch.from_numpy(pbr_target),                  # [10]
        }


def create_dataloaders(
    npz_path: str,
    batch_size: int = 128,
    min_k: int = 4,
    num_workers: int = 4,
) -> Tuple[DataLoader, DataLoader]:
    """Create training and validation DataLoaders from a preprocessed .npz file."""
    train_ds = ARCNetPaletteDataset(
        npz_path=npz_path, split="train", min_k=min_k, augment=True
    )
    val_ds = ARCNetPaletteDataset(
        npz_path=npz_path, split="val", min_k=min_k, augment=False
    )

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=False,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )
    return train_loader, val_loader
